"""Сборка кода в контекст для судьи.

Здесь была тихая поломка, стоившая ложного провала. Каждый файл резался
на 4000 символов, поверх стоял общий лимит 14000. При этом самый большой
прогон занимал 8821 символ — внутренний лимит не спасал от переполнения
ни разу, зато обрезал 4 файла из 7.

Судья получил email_validator.py, оборванный на `return _invalid("d`,
и написал безупречный по логике вывод: модуль не импортируется, QA
approved нерабочий код, балл 0.3. Код был целым: 4284 символа, лишние
284 отрезала обвязка. Тест не упал с ошибкой — он уверенно и подробно
обвинил исправно работающего агента.

Отсюда правило: контекст режем в одном месте, по общему бюджету, и
всегда оставляем видимую метку. Судья должен отличать конец файла от
конца бюджета — молчаливый обрыв он читает как оборванный код.
"""

MARK = "\n# ... [обрезано обвязкой теста, файл длиннее] ..."


def render_files(files: dict[str, str], budget: int = 40_000) -> str:
    """Склеивает файлы в один блок, укладываясь в budget символов.

    Целые файлы не режутся, пока хватает бюджета. Если не хватает —
    режется только то, что не влезло, и обрыв помечается MARK.
    """
    parts, left = [], budget
    for name, content in files.items():
        head = f"# {name}\n"
        left -= len(head)
        if left <= 0:
            parts.append(f"{head}{MARK}")
            break
        if len(content) <= left:
            parts.append(head + content)
            left -= len(content)
        else:
            parts.append(head + content[:left] + MARK)
            left = 0
    return "\n\n".join(parts)


def render_requirements(requirements: list[str]) -> str:
    """Подаёт требования как множество правил, а не как последовательность.

    Судья прочитал маркированный список как контракт порядка и снял балл
    за то, что код проверяет длину раньше числа собак. Спецификация такого
    не требует: единственное её условие про порядок — детерминированность,
    и она выполнена. Дефект был выдуман из вёрстки списка.
    """
    body = "\n".join(f"- {r}" for r in requirements)
    return ("REQUIREMENTS (неупорядоченное множество правил; порядок пунктов "
            "ниже ничего не предписывает — обязателен только тот порядок, "
            "который явно назван в самом тексте правила):\n" + body)
