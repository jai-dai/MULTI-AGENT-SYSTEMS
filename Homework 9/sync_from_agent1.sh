#!/bin/sh
# Перенести из Agent_1 то, что переиспользуется БЕЗ изменений.
#
# Agent_1 — место кодовой базы ОДИНОЧНОГО агента с RAG. Здесь живёт другой
# проект: мультиагентная система на протоколах. Общего у них ровно один слой —
# поиск и его обвязка, и только он и копируется. Правки в этот слой делаются
# ТАМ и приезжают сюда; обратное направление запрещено.
#
# Список явный, а не «скопировать всё»: hw9 добавляет своих агентов, свой
# супервизор и серверы протоколов, и любая автоматика вида `rsync каталог
# целиком` однажды затрёт их. Расхождение в retriever.py выглядит не как ошибка,
# а как «поиск стал хуже», поэтому копии не должны разъезжаться молча.
#
# --------------------------------------------------------------------------
# ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ
# --------------------------------------------------------------------------
#
# config.py — СВОЙ. Изъят из списка 2026-08-24, и это исправление настоящей
#   мины, а не наведение порядка. Здешний config.py содержит то, чего у Agent_1
#   нет и не будет: `search_mcp_port`, `report_mcp_port`, `acp_port`,
#   `protocol_host`. Один запуск этого скрипта со старым списком стирал их, и
#   система падала на AttributeError — то есть скрипт синхронизации ломал
#   систему, которую синхронизировал. Порты это не настройка, а адрес
#   инструмента: архитектура здесь другая, и конфигурация вслед за ней.
#
# requirements.txt — копируется, но дописывать в него НЕЛЬЗЯ: он приезжает
#   отсюда целиком. Всё, чего нет у Agent_1, живёт в requirements-protocols.txt.
#
# data/ и index/ — БОЛЬШЕ НЕ СИМЛИНКИ (2026-08-24). Были ссылками на Agent_1;
#   теперь свои копии, потому что это отдельный проект и его корпус не должен
#   меняться оттого, что кто-то переиндексировал соседний. Полтора и шесть
#   мегабайт — цена, которую стоит заплатить за то, чтобы домашка была целой
#   сама по себе. Пересобрать свою копию: `python ingest.py`.
#
#   ВНИМАНИЕ: изоляция на этом не заканчивается. Векторы живут в СЕРВЕРЕ Qdrant,
#   и разделяются они ИМЕНЕМ КОЛЛЕКЦИИ, а не каталогом. Пока у hw8, hw9 и hw10
#   в .env стоит `INDEX_DIR=index`, они пишут и читают одну коллекцию `index` на
#   сервере. Каталоги теперь свои, коллекция — ещё нет.
set -e
SRC="/Users/dhanika/Documents/VL/Agent_1"
DST="$(cd "$(dirname "$0")" && pwd)"

FILES="llm.py retriever.py vectorstore.py embeddings.py sparse.py translate.py
       ocr.py importance.py ingest.py preflight.py tools.py
       check_names.py .gitignore requirements.txt"

# Файлы, которые НАМЕРЕННО не синхронизируются. Про них скрипт не молчит:
# «не копируется» не должно означать «молча отстало на три месяца».
OWN="config.py"

for f in $FILES; do
    if [ -e "$SRC/$f" ]; then
        cp -p "$SRC/$f" "$DST/$f"
    else
        echo "  ! нет в Agent_1: $f"
    fi
done

for d in mailprep hooks; do
    [ -d "$SRC/$d" ] && rsync -a --delete --exclude '__pycache__' "$SRC/$d/" "$DST/$d/"
done

# Список приватных имён не копируется в git, но нужен локально стражу.
[ -f "$SRC/.private-names.txt" ] && cp -p "$SRC/.private-names.txt" "$DST/.private-names.txt"

echo "синхронизировано из Agent_1: $(echo $FILES | wc -w | tr -d ' ') файлов + mailprep/ + hooks/"

# Отчёт о расхождениях по НЕСИНХРОНИЗИРУЕМЫМ файлам. Молчание здесь означало бы,
# что независимость файла со временем превращается в его забытость.
for f in $OWN; do
    if [ -e "$SRC/$f" ] && ! diff -q "$SRC/$f" "$DST/$f" > /dev/null 2>&1; then
        added=$(diff "$SRC/$f" "$DST/$f" | grep -c '^>' || true)
        removed=$(diff "$SRC/$f" "$DST/$f" | grep -c '^<' || true)
        echo "  свой (не тронут): $f — здесь на $added строк больше, на $removed меньше, чем в Agent_1"
    fi
done
